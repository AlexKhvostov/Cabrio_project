<?php
/**
 * test_photo_logic.php
 * 
 * Тест логики обработки фото в разных контекстах
 */

// Включаем отображение ошибок
ini_set('display_errors', 1);
error_reporting(E_ALL);

echo "🔍 Тест логики обработки фото\n\n";

// Симулируем разные типы сообщений
$testMessages = [
    // 1. Фото в личных сообщениях
    [
        'type' => 'Личные сообщения',
        'chat' => ['type' => 'private'],
        'photo' => true,
        'text' => null,
        'expected' => 'execute() - с визиткой'
    ],
    // 2. Фото с "?" в групповом чате
    [
        'type' => 'Групповой чат',
        'chat' => ['type' => 'group'],
        'photo' => true,
        'text' => '?',
        'expected' => 'executeGroupPhoto() - без визитки'
    ],
    // 3. Простое фото в групповом чате (должно игнорироваться)
    [
        'type' => 'Групповой чат',
        'chat' => ['type' => 'group'],
        'photo' => true,
        'text' => null,
        'expected' => 'ИГНОРИРУЕТСЯ'
    ],
    // 4. Фото с другим текстом в групповом чате
    [
        'type' => 'Групповой чат',
        'chat' => ['type' => 'group'],
        'photo' => true,
        'text' => 'Привет!',
        'expected' => 'ИГНОРИРУЕТСЯ'
    ]
];

foreach ($testMessages as $i => $test) {
    echo "=== Тест " . ($i + 1) . ": " . $test['type'] . " ===\n";
    echo "📱 Тип чата: " . $test['chat']['type'] . "\n";
    echo "📸 Есть фото: " . ($test['photo'] ? 'Да' : 'Нет') . "\n";
    echo "💬 Текст: " . ($test['text'] ?? 'Нет') . "\n";
    echo "🎯 Ожидаемый результат: " . $test['expected'] . "\n\n";
}

echo "🎯 Правильная логика:\n";
echo "1. Фото + '?' в группе → executeGroupPhoto() (без визитки)\n";
echo "2. Просто фото в личных → execute() (с визиткой)\n";
echo "3. Просто фото в группе → ИГНОРИРУЕТСЯ\n";
echo "4. Фото + другой текст в группе → ИГНОРИРУЕТСЯ\n";
echo "5. Любые текстовые сообщения в группе → ИГНОРИРУЕТСЯ\n\n";

echo "✅ Бот реагирует ТОЛЬКО на:\n";
echo "   • Фото с '?' в групповом чате (распознавание номера)\n";
echo "   • Просто фото в личных сообщениях (распознавание + визитка)\n";
echo "   • Текстовые сообщения в личных (поиск по номеру)\n";
echo "   • Команды в любом чате (/start, /help, /test)\n";
echo "   • Присоединение/выход участников (автоматически)\n";
echo "   • Уведомления о событиях (от приложения)\n\n";

echo "🚫 Бот НЕ реагирует на:\n";
echo "   • Обычные текстовые сообщения в группе\n";
echo "   • Простые фото в группе (без '?')\n";
echo "   • Любые другие сообщения в группе\n";
?> 