<?php
/**
 * test_group_photo.php
 * 
 * Тест группового функционала с фото и "?"
 */

// Включаем отображение ошибок
ini_set('display_errors', 1);
error_reporting(E_ALL);

echo "🔍 Тест группового функционала\n\n";

// Загружаем конфигурацию бота
require_once __DIR__ . '/../bot/config.php';

// Симулируем разные ответы от API для группового чата
$testResponses = [
    // Автомобиль найден
    [
        'success' => true,
        'ocr_success' => true,
        'found' => true,
        'plate' => '0070MX7',
        'status' => 'Активный'
    ],
    // Автомобиль не найден
    [
        'success' => true,
        'ocr_success' => true,
        'found' => false,
        'plate' => 'ABC123'
    ]
];

foreach ($testResponses as $i => $result) {
    echo "=== Групповой тест " . ($i + 1) . " ===\n";
    
    if (!$result['success']) {
        echo "❌ Не удалось обработать фото\n\n";
        continue;
    }
    
    if (!$result['ocr_success']) {
        echo "❌ Не удалось распознать номер на фото\n\n";
        continue;
    }
    
    // Номер распознан успешно
    $plate = $result['plate'];
    
    // Формируем структурированный ответ для группы (БЕЗ вопроса о визитке)
    $text = "Распознан номер\n";
    $text .= "🚗 " . $plate . "\n";
    
    if ($result['found']) {
        // Автомобиль найден в базе
        $status = $result['status'] ?? 'Неизвестно';
        $text .= "✅ " . $status;
    } else {
        // Автомобиль не найден в базе
        $text .= "🚫 Нет в клубе";
    }
    
    echo $text . "\n\n";
    echo "📝 Примечание: В групповом чате НЕ показывается вопрос о визитке\n\n";
}

echo "🎯 Логика работы:\n";
echo "1. Пользователь отправляет фото с текстом '?' в групповой чат\n";
echo "2. Бот автоматически распознает номер\n";
echo "3. Проверяет наличие в базе данных\n";
echo "4. Отправляет результат в групповой чат\n";
echo "5. НЕ предлагает оставить визитку (только информационный ответ)\n\n";

echo "🔄 Сравнение с личными сообщениями:\n";
echo "📱 Личные сообщения (просто фото): распознавание + ВОПРОС о визитке\n";
echo "👥 Групповой чат (фото + '?'): распознавание + БЕЗ вопроса о визитке\n";
?> 